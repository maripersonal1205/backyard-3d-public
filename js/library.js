import * as THREE from "three";
import { GLTFLoader } from "three/addons/loaders/GLTFLoader.js";
import { LIBRARY } from "./config.js";

// The Library: item types that aren't part of backyard.glb.
//   "lib:<id>"  pre-made items listed in library/library.json (see LIBRARY_SPEC.md)
//   "imp:<id>"  models imported from a file (ctx.backend.imports: this browser,
//               or shared with everyone in the shared app), or created with AI
//               (listed under their own category)
// Models load only when first needed (placed, or pictured in the Library tab).
// Library models face +z; they are recentred so they rest on y = 0.
const MANIFEST = "library/library.json";

export const libKey = (id) => "lib:" + id;
export const AI_CATEGORY = "Generated by AI";
export const impKey = (id) => "imp:" + id;

// Wrap a loaded model so its base sits centred on the origin at `scale`.
// `keepHeight` items (mounted ones, like a canopy) are only centred on x/z and
// keep the height they were modelled at above the ground.
export function normalize(root, scale = 1, keepHeight = false) {
  root.updateMatrixWorld(true);
  const box = new THREE.Box3().setFromObject(root);
  const c = box.getCenter(new THREE.Vector3());
  root.position.x -= c.x;
  if (!keepHeight) root.position.y -= box.min.y;
  root.position.z -= c.z;
  const scaled = new THREE.Group();
  scaled.scale.setScalar(scale);
  scaled.add(root);
  const object = new THREE.Group();
  object.add(scaled);
  object.traverse((o) => {
    if (o.isMesh) { o.castShadow = true; o.receiveShadow = true; }
  });
  return object;
}

export async function parseGLB(buffer) {
  const gltf = await new GLTFLoader().parseAsync(buffer, "");
  return gltf.scene;
}

export async function createLibrary(ctx) {
  const { items } = ctx;
  const root = new THREE.Group();
  root.name = "library-items";
  ctx.model.add(root); // inside the model so picking and double-click treat them like other items

  const entries = new Map(); // key -> { key, label, category, tags, url?, record?, thumbnail? }
  const loading = new Map(); // key -> Promise<boolean>

  try {
    const res = await fetch(MANIFEST, { cache: "no-cache" });
    if (res.ok) {
      const data = await res.json();
      for (const e of data.items || []) {
        if (!e.id || !e.file || LIBRARY.hide.includes(e.id)) continue; // the yard's file can leave items out
        entries.set(libKey(e.id), {
          key: libKey(e.id), label: e.label || e.id,
          category: LIBRARY.asAI.includes(e.id) ? AI_CATEGORY : e.category || "Other",
          tags: e.tags || [], url: new URL(e.file, new URL(MANIFEST, location.href)).href,
          thumbnail: e.thumbnail ? new URL(e.thumbnail, new URL(MANIFEST, location.href)).href : null,
          keepHeight: e.keepHeight === true,
        });
      }
    }
  } catch (err) {
    console.warn("Library list couldn't be read", err);
  }
  // Items the yard's file adds for that yard only (the demo's fig tree).
  for (const e of LIBRARY.extra || []) {
    entries.set(libKey(e.id), {
      key: libKey(e.id), label: e.label, category: e.category || "Other", tags: e.tags || [],
      url: new URL(e.file, location.href).href,
      thumbnail: e.thumbnail ? new URL(e.thumbnail, location.href).href : null,
      keepHeight: false,
    });
  }
  try {
    for (const r of await ctx.backend.imports.list()) addImportEntry(r);
  } catch (err) {
    console.warn("Imported models couldn't be read", err);
  }

  function addImportEntry(r) {
    entries.set(impKey(r.id), {
      key: impKey(r.id), label: r.label, category: r.ai ? AI_CATEGORY : "Imported", tags: [], record: r, thumbnail: r.thumbnail || null,
      canDelete: r.canDelete !== false,
    });
  }

  function register(key, object) {
    const e = entries.get(key);
    items.addTemplate(key, { label: e.label }, object, root);
    if (!e.thumbnail) {
      e.thumbnail = ctx.renderThumbnail(items.templates[key], 1);
      ctx.emit("thumbs-changed");
    }
  }

  // Load a type's model if it isn't loaded yet. Resolves false if it can't be.
  function ensure(key) {
    if (items.templates[key]) return Promise.resolve(true);
    const e = entries.get(key);
    if (!e) return Promise.resolve(false);
    if (!loading.has(key)) {
      const job = (async () => {
        const scene = e.record?.data
          ? await parseGLB(e.record.data)
          : (await new GLTFLoader().loadAsync(e.record?.url || e.url)).scene;
        register(key, normalize(scene, e.record?.scale ?? 1, e.keepHeight));
        return true;
      })().catch((err) => {
        console.warn(`Couldn't load ${e.label}`, err);
        e.failed = true;
        loading.delete(key);
        return false;
      });
      loading.set(key, job);
    }
    return loading.get(key);
  }

  async function ensureAll(keys) {
    const ok = await Promise.all(keys.map(ensure));
    return keys.filter((_, i) => !ok[i]);
  }

  // Pictures for Library rows that have none yet, one model at a time.
  let picturing = false;
  async function pictureMissing() {
    if (picturing) return;
    picturing = true;
    for (const e of entries.values()) if (!e.thumbnail && !e.failed) await ensure(e.key);
    picturing = false;
  }

  // A delivered picture that doesn't load (e.g. the file is missing): draw our own.
  function thumbnailFailed(key) {
    const e = entries.get(key);
    if (!e?.thumbnail || e.thumbnail.startsWith("data:")) return;
    e.thumbnail = null;
    if (items.templates[key]) {
      e.thumbnail = ctx.renderThumbnail(items.templates[key], 1);
      ctx.emit("thumbs-changed");
    } else {
      pictureMissing();
    }
  }

  async function addImport({ label, data, scale, thumbnail, ai = false }) {
    const record = await ctx.backend.imports.add({ label, data, scale, thumbnail });
    addImportEntry({ ...record, ai });
    return impKey(record.id);
  }

  async function removeImport(key) {
    const e = entries.get(key);
    if (!e?.record) return;
    await ctx.backend.imports.remove(e.record.id);
    entries.delete(key);
    delete items.templates[key]; // so undo can't bring back an item whose model is gone
  }

  return {
    get entries() { return [...entries.values()]; },
    get: (key) => entries.get(key) || null,
    ensure, ensureAll, pictureMissing, thumbnailFailed, addImport, removeImport,
  };
}
