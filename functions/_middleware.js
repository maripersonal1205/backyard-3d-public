// Every request to the shared app (the page, the model, pictures and /api)
// passes through here first:
//  1. The family passcode gate. Without a valid "unlocked" cookie you only get
//     the passcode page (or a 401 for /api). The right passcode unlocks the
//     device for a day (Mari's choice): the cookie holds its expiry time signed
//     with an HMAC keyed by the passcode, so it can't be extended, and changing
//     PASSCODE locks every device out at once. Wrong guesses are limited per IP.
//  2. For /api: makes sure the database tables exist. There are no accounts
//     or names: everyone with the passcode sees and can change everything.
//
// Environment (Pages → Settings → Variables and bindings):
//   PASSCODE  the family passcode (a secret)
//   DB        D1 database binding
//   FILES     KV namespace binding (imported / generated model files)
//   OPEN_AI_KEY  OpenAI API key (a secret; optional: without it, creating with AI is off)

const UNLOCK_COOKIE = "backyard_unlocked";
const YEAR = 365 * 24 * 3600;
const UNLOCK_SECONDS = 24 * 3600; // how long a device stays unlocked
const MAX_FAILURES = 20; // wrong passcodes per IP address per hour

const SCHEMA = [
  `CREATE TABLE IF NOT EXISTS plans (
     id TEXT PRIMARY KEY, owner TEXT, name TEXT NOT NULL, layout TEXT NOT NULL,
     created_at INTEGER NOT NULL, updated_at INTEGER NOT NULL)`,
  `CREATE TABLE IF NOT EXISTS imports (
     id TEXT PRIMARY KEY, owner TEXT, label TEXT NOT NULL, scale REAL NOT NULL,
     thumbnail TEXT, created_at INTEGER NOT NULL)`,
  `CREATE TABLE IF NOT EXISTS unlock_failures (ip TEXT NOT NULL, at INTEGER NOT NULL)`,
  // Items being created with AI (api/generate, functions/_astra.js). stage: build | review
  // (reviewing: claimed, review being started); status: working | ready | failed | done.
  // The finished files wait in KV (gen/<id>.glb, .png) until someone adds the item;
  // import_id is the Library item it became ("Generated by AI" in the Library).
  `CREATE TABLE IF NOT EXISTS generations (
     id TEXT PRIMARY KEY, owner TEXT, name TEXT NOT NULL, prompt TEXT, kind TEXT NOT NULL,
     container TEXT, response TEXT, stage TEXT NOT NULL, stage_at INTEGER NOT NULL,
     item_id TEXT, status TEXT NOT NULL, progress INTEGER NOT NULL DEFAULT 0, error TEXT,
     cost_cents REAL NOT NULL DEFAULT 0, import_id TEXT, created_at INTEGER NOT NULL, updated_at INTEGER NOT NULL)`,
];

export function json(body, status = 200, headers = {}) {
  return new Response(JSON.stringify(body), {
    status,
    headers: { "content-type": "application/json; charset=utf-8", "cache-control": "no-store", ...headers },
  });
}

export const cookie = (name, value, maxAge = YEAR) =>
  `${name}=${value}; Path=/; Max-Age=${maxAge}; HttpOnly; Secure; SameSite=Lax`;

export function readCookie(request, name) {
  const all = request.headers.get("cookie") || "";
  return new RegExp(`(?:^|;\\s*)${name}=([^;]+)`).exec(all)?.[1] || null;
}

let schemaReady = null;
const ensureSchema = (env) =>
  (schemaReady ||= env.DB.batch(SCHEMA.map((sql) => env.DB.prepare(sql))).catch((err) => {
    schemaReady = null;
    throw err;
  }));

export async function onRequest(context) {
  const { request, env } = context;
  const url = new URL(request.url);
  const isApi = url.pathname.startsWith("/api/");
  try {
    if (!env.PASSCODE) return lockedPage("Your passcode hasn't been set up yet.", 503);

    if (url.pathname === "/__unlock" && request.method === "POST") return unlock(request, env);

    if (!(await validUnlock(readCookie(request, UNLOCK_COOKIE), env.PASSCODE))) {
      return isApi ? json({ error: "Locked. Enter your passcode." }, 401) : lockedPage();
    }
    if (!isApi) return context.next();

    await ensureSchema(env);
    return await context.next();
  } catch (err) {
    console.error(err);
    return isApi ? json({ error: "Something went wrong on the server." }, 500) : lockedPage("Something went wrong. Try again.", 500);
  }
}

// ---- Passcode ----

const enc = new TextEncoder();
async function hmac(passcode, message) {
  const key = await crypto.subtle.importKey("raw", enc.encode(passcode), { name: "HMAC", hash: "SHA-256" }, false, ["sign"]);
  const sig = new Uint8Array(await crypto.subtle.sign("HMAC", key, enc.encode(message)));
  return btoa(String.fromCharCode(...sig)).replace(/\+/g, "-").replace(/\//g, "_").replace(/=+$/, "");
}

// Unlock cookie value: "<expiry seconds>.<HMAC of it>".
const unlockValue = async (passcode, exp) => `${exp}.${await hmac(passcode, "backyard-unlocked:" + exp)}`;
async function validUnlock(value, passcode) {
  const exp = Number(/^(\d+)\./.exec(value || "")?.[1]);
  if (!exp || exp < Date.now() / 1000) return false;
  return sameText(value, await unlockValue(passcode, exp));
}

// Compare without leaking where the first difference is.
function sameText(a, b) {
  let diff = a.length ^ b.length;
  for (let i = 0; i < Math.max(a.length, b.length); i++) diff |= (a.charCodeAt(i) || 0) ^ (b.charCodeAt(i) || 0);
  return diff === 0;
}

async function unlock(request, env) {
  await ensureSchema(env);
  const ip = request.headers.get("cf-connecting-ip") || "unknown";
  const hourAgo = Date.now() - 3600_000;
  await env.DB.prepare("DELETE FROM unlock_failures WHERE at < ?").bind(hourAgo).run();
  const { n } = await env.DB.prepare("SELECT COUNT(*) AS n FROM unlock_failures WHERE ip = ?").bind(ip).first();
  if (n >= MAX_FAILURES) return lockedPage("Too many wrong tries. Wait an hour and try again.", 429);

  const form = await request.formData().catch(() => null);
  const given = String(form?.get("passcode") || "");
  // Compare HMACs rather than the raw strings, so timing says nothing about the passcode.
  const [a, b] = await Promise.all([hmac(given, "check"), hmac(env.PASSCODE, "check")]);
  if (!given || !sameText(a, b)) {
    await env.DB.prepare("INSERT INTO unlock_failures (ip, at) VALUES (?, ?)").bind(ip, Date.now()).run();
    await new Promise((r) => setTimeout(r, 600)); // slow down guessing
    return lockedPage("That passcode isn't right.", 401);
  }
  const exp = Math.floor(Date.now() / 1000) + UNLOCK_SECONDS;
  return new Response(null, {
    status: 303,
    headers: {
      location: "/",
      "set-cookie": cookie(UNLOCK_COOKIE, await unlockValue(env.PASSCODE, exp), UNLOCK_SECONDS),
      "cache-control": "no-store",
    },
  });
}

